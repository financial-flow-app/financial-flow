// Builds src/formula-map.js from the template: for each Month-End input row, the formula in
// column C, the formula in column D, and how each reference moves per column after that.
// Usage: node scripts/build-formula-map.mjs fixtures/ffos-template.xlsx

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { openWorkbook, sheetXml, readCells } from '../src/xlsx.js';
import { makeRef } from '../src/cellref.js';

const mapFile = new URL('../src/formula-map.js', import.meta.url);
if (!existsSync(mapFile)) writeFileSync(mapFile, 'export const FORMULA_MAP = {};\n');
const { MONTH_END_INPUT_ROWS, FIRST_COL, inferSteps } = await import('../src/ffos.js');

const wb = await openWorkbook(readFileSync(process.argv[2]));
const cells = readCells(await sheetXml(wb, 'Month-End'), wb.sharedStrings);
const map = {};
for (const row of MONTH_END_INPUT_ROWS) {
  const c = cells.get(makeRef(FIRST_COL, row))?.formula?.text ?? null;
  const d = cells.get(makeRef(FIRST_COL + 1, row))?.formula?.text ?? null;
  const e = cells.get(makeRef(FIRST_COL + 2, row))?.formula?.text ?? null;
  if (c == null && d == null) continue;
  const steps = d != null ? inferSteps(d, e) : null;
  if (d != null && !steps) throw new Error(`Row ${row}: columns D and E don't follow one pattern.`);
  map[row] = { first: c, next: d, steps: steps && steps.map((s) => [s.dc, s.dr]) };
}
const out =
  '// Generated by scripts/build-formula-map.mjs from the FFOS 3.6 template. Do not edit.\n' +
  '// Month-End input rows: the automatic formula in column C (first), in column D (next),\n' +
  '// and how each reference in `next` moves per column.\n' +
  'export const FORMULA_MAP = {\n' +
  Object.entries(map).map(([r, v]) => ` ${r}: ${JSON.stringify(v)},\n`).join('') +
  '};\n';
writeFileSync(mapFile, out);
console.log(`rows with formulas: ${Object.keys(map).join(', ')}`);
